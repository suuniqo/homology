    def test_circular_cloud(self) -> None:
        """Checks that the final complex fills the convex hull."""
        built = self.build(self.circular_cloud())

        self.assertEqual(
            built.filtration(0.0).face_set,
            {Simplex((vertex,)) for vertex in range(20)},
        )

        final = built.filtration(built.threshold_values()[-1])

        self.assertEqual(final.dim, 2)
        self.assertEqual(final.euler_characteristic, 1)
        self.assertEqual(final.connected_components(), 1)
